function get_phrases($words, $length = 3) {
    $phrases = [];
    $count = count($words);
    
    for ($i = 0; $i <= $count - $length; $i++) {
        // Slice a window of words and join them
        $phrase = implode(' ', array_slice($words, $i, $length));
        $phrases[] = $phrase;
    }
    
    return $phrases;
}

function strip_common_words($text, $extra_stops = []) {
    // 1. A comprehensive list of common English "stop words"
    $stop_words = [
        'a', 'an', 'and', 'are', 'as', 'at', 'be', 'but', 'by', 'for', 'if', 'in',
        'is', 'it', 'into', 'is', 'it', 'no', 'not', 'of', 'on', 'or', 'such',
        'that', 'the', 'their', 'then', 'there', 'these', 'they', 'this', 'to',
        'was', 'will', 'with', 'from', 'with', 'about',
    ];

    // Merge with any custom words you want to exclude
    $stop_words = array_merge($stop_words, $extra_stops);

    // 2. Remove punctuation and convert to lowercase
    $text = preg_replace('/[^\p{L}\p{N}\s]/u', '', strtolower($text));

    // 3. Split into individual words
    $words = preg_split('/\s+/', $text, -1, PREG_SPLIT_NO_EMPTY);

global $phrase_counts;
$ph = get_phrases($words, $length = 3);
foreach ($ph as $p) {
    //$phrase_counts[$p] = ($phrase_counts[$p] ?? 0) + 1;

    $parts = explode(' ', $p);

    // Count how many words in this specific phrase are in our stop_words list
    $stop_count = 0;
    foreach ($parts as $w) {
        if (in_array($w, $stop_words)) $stop_count++;
    }

    if ($stop_count < 2)
        $phrase_counts[$p] = ($phrase_counts[$p] ?? 0) + 1;
}

    // 4. Filter out the stop words
    $filtered_words = array_filter($words, function($word) use ($stop_words) {
        return !in_array($word, $stop_words);
    });

    return implode(' ', $filtered_words);
}


